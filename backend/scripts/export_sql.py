"""Regenerate the two SQL reference files from the code, so documentation never drifts from what runs.

* sql/query_catalogue.sql  - every SQL Analytics report (app/services/analytics.py) and the views (app/views.py)
* sql/schema_postgresql.sql - full PostgreSQL DDL from the Alembic migrations (offline mode, no server needed)

Usage (from backend/):  python -m scripts.export_sql
"""
from __future__ import annotations

import contextlib
import io
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

from alembic import command  # noqa: E402
from alembic.config import Config  # noqa: E402

from app.config import BACKEND_DIR  # noqa: E402
from app.services.analytics import REPORTS  # noqa: E402
from app.views import VIEWS  # noqa: E402


def catalogue() -> str:
    out = ["-- CancerBioMap SQL query catalogue",
           "-- Generated by scripts/export_sql.py from app/services/analytics.py and app/views.py",
           "-- (the same statements the API executes). Parameters use :name bind syntax; the API binds them,",
           "-- never interpolates. Portable SQL: verified on PostgreSQL 16 and SQLite.", ""]
    out += ["-- ===================================================================== views", ""]
    for name, ddl in VIEWS.items():
        out += [f"-- {name}", ddl.strip() + ";", ""]
    out += ["-- ===================================================================== reports", ""]
    for i, r in enumerate(REPORTS.values(), start=1):
        out.append(f"-- Q{i}. {r.title}")
        out.append(f"--     {r.description}")
        if r.params:
            out.append("--     Parameters: " + ", ".join(
                f":{p.name} ({p.description}; default {p.default})" for p in r.params))
        out.append(f"--     Concepts: {', '.join(r.concepts)}")
        out.append(r.sql.strip() + ";")
        out.append("")
    return "\n".join(out)


def postgres_ddl() -> str:
    cfg = Config(str(BACKEND_DIR / "alembic.ini"))
    cfg.set_main_option("script_location", str(BACKEND_DIR / "alembic"))
    cfg.attributes["database_url"] = "postgresql+psycopg://user@localhost/cancerbiomap"
    buf = io.StringIO()
    cfg.output_buffer = buf
    with contextlib.redirect_stderr(io.StringIO()):
        command.upgrade(cfg, "head", sql=True)
    header = ("-- CancerBioMap PostgreSQL schema\n"
              "-- Generated by scripts/export_sql.py from the Alembic migrations (alembic upgrade head --sql).\n"
              "-- Verified by applying the migrations to PostgreSQL 16 and comparing every API endpoint with SQLite.\n\n")
    return header + buf.getvalue()


if __name__ == "__main__":
    (BACKEND_DIR / "sql" / "query_catalogue.sql").write_text(catalogue())
    (BACKEND_DIR / "sql" / "schema_postgresql.sql").write_text(postgres_ddl())
    print("Wrote sql/query_catalogue.sql and sql/schema_postgresql.sql")
